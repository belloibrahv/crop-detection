/**
 * Custom service worker for AgroScan NG.
 *
 * Strategy:
 *  - App shell (HTML / JS / CSS / icons) → CacheFirst via Workbox precaching.
 *  - API calls (/api/*) → NetworkOnly (diagnoses always require connectivity).
 *  - Navigation fallback → serve the cached index.html (SPA routing).
 *
 * Vite-plugin-pwa injects the precache manifest at build time via
 * self.__WB_MANIFEST.
 */
import { cleanupOutdatedCaches, precacheAndRoute, createHandlerBoundToURL } from 'workbox-precaching'
import { registerRoute, NavigationRoute } from 'workbox-routing'
import { NetworkOnly, CacheFirst } from 'workbox-strategies'
import { CacheableResponsePlugin } from 'workbox-cacheable-response'
import { clientsClaim } from 'workbox-core'

declare let self: ServiceWorkerGlobalScope & { __WB_MANIFEST: Array<{ url: string; revision: string | null }> }

// Force the waiting service worker to become the active service worker.
;(self as any).addEventListener('install', () => {
  ;(self as any).skipWaiting()
})
clientsClaim()

// Precache the app shell generated by Vite
precacheAndRoute(self.__WB_MANIFEST)
cleanupOutdatedCaches()

// API requests are always network-only (live inference required)
registerRoute(
  ({ url }) => url.pathname.startsWith('/api/'),
  new NetworkOnly()
)

// Static assets: cache-first with a 30-day expiry
registerRoute(
  ({ request }) =>
    request.destination === 'image' ||
    request.destination === 'font' ||
    request.destination === 'style' ||
    request.destination === 'script',
  new CacheFirst({
    cacheName: 'static-assets-v1',
    plugins: [new CacheableResponsePlugin({ statuses: [0, 200] })],
  })
)

// SPA fallback: serve precached index.html for navigation requests
const navigationRoute = new NavigationRoute(
  createHandlerBoundToURL('/index.html')
)
registerRoute(navigationRoute)
